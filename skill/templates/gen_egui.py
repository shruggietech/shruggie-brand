class EguiAdapterError(ValueError):
    pass


def _require(condition, message):
    if not condition:
        raise EguiAdapterError(message)


def _read_json(path):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise EguiAdapterError("invalid UTF-8 JSON at %s: %s" % (path, error)) from error


def _write_text(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(value.rstrip("\n") + "\n")


def _write_json(path, value):
    _write_text(path, json.dumps(value, indent=2, ensure_ascii=False))


def _rust_ident(value):
    value = re.sub(r"[^a-zA-Z0-9_]", "_", value).strip("_").lower()
    if not value or value[0].isdigit():
        value = "brand_" + value
    return value


def _rgb(value):
    _require(isinstance(value, str) and re.fullmatch(r"#[0-9A-Fa-f]{6}", value),
             "expected a six-digit color, got %r" % value)
    return tuple(int(value[index:index + 2], 16) for index in (1, 3, 5))


def _color(name, value):
    red, green, blue = _rgb(value)
    return "            %s: egui::Color32::from_rgb(%d, %d, %d)," % (name, red, green, blue)


