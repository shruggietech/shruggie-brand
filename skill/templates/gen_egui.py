def verify_egui_adapter(kit_path):
    kit = Path(kit_path)
    problems = []
    root = kit / "native" / "egui"
    try:
        required = {
            "Cargo.toml", "Cargo.lock", "README.md", "adapter.json", "support-matrix.json", "version-policy.json",
            "src/lib.rs", "src/tokens.rs", "src/components.rs", "tests/adapter.rs",
        }
        actual = {path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file()}
        missing = required - actual
        _require(not missing, "egui adapter is missing: %s" % ", ".join(sorted(missing)))
        manifest = _read_json(root / "adapter.json")
        support = _read_json(root / "support-matrix.json")
        policy = validate_version_policy(_read_json(root / "version-policy.json"))
        brand = _read_json(kit / "brand.json")
        catalog = load_component_catalog()
        metadata = skill_metadata()
        _require(manifest.get("adapter_version") == metadata["egui_adapter"], "egui adapter version disagrees with compiler metadata")
        _require(manifest.get("compiler_version") == metadata["version"], "egui adapter compiler version disagrees with compiler metadata")
        _require(manifest.get("brand_version") == brand.get("version", "1.0.0"), "egui adapter brand version disagrees")
        _require(manifest.get("component_recipe_version") == catalog.get("version"), "egui adapter component recipe version disagrees")
        _require(manifest.get("interface_canon_version") == load_interface_canon().get("version"), "egui adapter Interface Canon version disagrees")
        _require(manifest.get("version_policy_version") == policy["version"], "egui adapter version policy disagrees")
        versions = {
            "brand_canon": manifest.get("brand_canon_version"),
            "interface_canon": manifest.get("interface_canon_version"),
            "component_recipes": manifest.get("component_recipe_version"),
            "web_react_adapter": metadata["web_react_adapter"],
            "egui_adapter": manifest.get("adapter_version"),
            "compiler": manifest.get("compiler_version"),
            "brand": manifest.get("brand_version"),
        }
        _require(manifest.get("compatibility") == validate_version_combination(versions, policy),
                 "egui adapter compatibility record disagrees with version policy")
        _require(support.get("adapter_version") == manifest.get("adapter_version"),
                 "egui support matrix adapter version disagrees")
        _require(support.get("component_recipe_version") == catalog.get("version"),
                 "egui support matrix recipe version disagrees")
        records = support.get("components") or []
        _require(len(records) == len(COMPONENT_IDS) and {item.get("component") for item in records} == set(COMPONENT_IDS),
                 "egui support recipe coverage is incomplete")
        for item in records:
            _require(item.get("status") in {"supported", "adapted", "unsupported"}, "egui support status is invalid")
            _require(item.get("proof") in {"passed", "pending"}, "egui proof status is invalid")
            if item["status"] == "unsupported":
                _require(item.get("symbol") is None, "unsupported egui recipe cannot claim a symbol")
            else:
                _require(isinstance(item.get("symbol"), str) and item["symbol"], "supported egui recipe lacks a symbol")
                _require(item.get("proof") == "passed" and "egui-kittest-rendered-state" in item.get("evidence", []),
                         "implemented egui recipe lacks rendered-state proof")
        cargo = (root / "Cargo.toml").read_text(encoding="utf-8")
        _require('egui = "=%s"' % EGUI_VERSION in cargo and 'egui_kittest = "=%s"' % EGUI_VERSION in cargo,
                 "egui Cargo dependencies are not pinned exactly")
        _require('rust-version = "%s"' % RUST_VERSION in cargo,
                 "egui Cargo MSRV disagrees with the adapter contract")
        expected_lock = LOCKFILE_TEMPLATE.read_text(encoding="utf-8").replace(
            "{{crate_name}}", manifest["crate"]["name"]
        )
        _require((root / "Cargo.lock").read_text(encoding="utf-8") == expected_lock,
                 "egui Cargo.lock disagrees with the deterministic adapter lockfile")
        source = (root / "src" / "lib.rs").read_text(encoding="utf-8") + (root / "src" / "components.rs").read_text(encoding="utf-8")
        _require("React" not in source and "className" not in source, "egui source emulates a web adapter")
    except (EguiAdapterError, OSError, UnicodeError, KeyError, TypeError, ValueError) as error:
        problems.append(str(error))
    return problems


