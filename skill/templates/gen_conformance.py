#!/usr/bin/env python3
"""Generate deterministic cross-host conformance fixtures for one brand kit."""

import hashlib
import json
import re
import sys
import textwrap
from pathlib import Path

from conformance_contract import evaluate_trace, load_policy, sha256_file


HERE = Path(__file__).resolve().parent
DECISIONS = HERE.parent / "references" / "conformance-baseline-decisions.json"
SAFE_CRATE = re.compile(r"[^a-z0-9_]+")
SOURCE_REVISION = re.compile(r"^[0-9a-f]{40,64}$")


def _write_text(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)


def _write_json(path, payload):
    _write_text(path, json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=False) + "\n")


def _read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


